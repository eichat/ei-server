-- Відкликання сесій: зміна пароля виганяє старі токени.
--
-- Токени stateless (HMAC, без БД — див. коментар над SESSION_SECRET у server.js),
-- тож `destroySessionsForNick` була заглушкою: НІЩО не відкликало токен. Зміна
-- пароля лишала викрадену сесію робочою — тобто головний засіб «мене зламали,
-- міняю пароль» не працював. Бан і видалення акаунта кликали ту саму заглушку.
--
-- Стало: у токені вже є час випуску (payload.t), а тут зберігається межа —
-- токени, старіші за неї, недійсні. Перевірка лишається синхронною й без
-- запиту до БД: значення тримаються в пам'яті (Map), а звідси читаються при
-- старті, тож відкликання переживає рестарт і засинання Render.
--
-- Ставиться і НОВИМ акаунтам: інакше повторна реєстрація звільненого ніка
-- воскресила б токени його попереднього власника.
alter table public.users add column if not exists tokens_valid_from bigint;
