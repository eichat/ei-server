-- Синхронізація ВЛАСНИХ повідомлень між пристроями одного акаунта.
--
-- Навіщо. Багатопристроєвість (multi_device.sql) розвела вхідні: те, що
-- написали ТОБІ, приходить на всі твої пристрої. Але вихідні лишились
-- однопристроєвими — надіслане з десктопа на телефоні не зʼявлялось узагалі.
-- Саме так це й виглядало в першому живому тесті: адресат отримував, другий
-- власний пристрій не бачив нічого.
--
-- Чому ОКРЕМА колонка, а не `delivered_devices`. Той масив відповідає на
-- питання «чи забрав це пристрій ОТРИМУВАЧА» — на ньому тримається догін
-- вхідних. Дописувати туди ще й пристрої відправника означало б змішати два
-- різні питання в одному полі: збіг ідентифікаторів між акаунтами (а в тестах
-- вони бувають однакові, на кшталт `D1`) тихо позначив би чуже повідомлення
-- доставленим. Помилки не було б — просто повідомлення зникло б.
alter table messages add column if not exists synced_devices text[] default '{}';

comment on column messages.synced_devices is
  'Пристрої АВТОРА, які вже отримали копію власного повідомлення. '
  'Окремо від delivered_devices (там пристрої отримувача).';
