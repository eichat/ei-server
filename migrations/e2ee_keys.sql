-- Наскрізне шифрування ОСОБИСТИХ чатів: публічний ключ пристрою (02.09.2026)
--
-- Модель навмисно найпростіша з можливих, і кожне спрощення має причину:
--  • ключ ЛИШЕ на пристрої, без резервної копії й без фрази — бо в EION
--    одночасно активний тільки один пристрій (другий вхід вибиває перший),
--    а доставлені особисті повідомлення сервер більше не надсилає, тож і
--    сьогодні новий пристрій старої переписки не бачить. Шифрування нічого
--    не відбирає;
--  • тут зберігається ТІЛЬКИ публічний ключ. Приватний лишається у сховищі
--    ОС на пристрої й до нас не потрапляє ніколи;
--  • групи НЕ шифруються: там /group/messages віддає історію будь-якому
--    пристрою, і ключ на пристрій зробив би її нечитабельною.
--
-- Опортуністично: хто ключа не опублікував (стара збірка) — тому пишуть
-- відкритим текстом, як і раніше. Ніякого дня переходу.

alter table users add column if not exists e2ee_pubkey text;

comment on column users.e2ee_pubkey is
  'Публічний ключ X25519 (base64url) пристрою, на якому користувач востаннє увійшов. Приватного ключа в нас немає.';
